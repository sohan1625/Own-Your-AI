"""Citation resolution module.

Responsible for:
- Mapping cited chunk IDs in generated answers to exact source file paths, page numbers, and character spans.
- Verifying that every cited chunk ID exists within the set of retrieved candidate passages.
- Invalidating or flagging citations that reference chunks outside the retrieved context.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Dict, List


@dataclass
class CitationResult:
    """Result of citation mapping.

    Attributes:
        answer: The original answer text (unchanged).
        valid_citations: List of mappings for each cited ID that exists in *chunks*.
            Each mapping is a dict with keys ``id``, ``file``, ``page``, ``start_char``, ``end_char``.
        dropped_citations: List of cited IDs that were not found in *chunks*.
        has_invalid: ``True`` if any citation was dropped, otherwise ``False``.
    """

    answer: str
    valid_citations: List[Dict[str, Any]]
    dropped_citations: List[str]
    has_invalid: bool


def _extract_citation_ids(answer: str) -> List[str]:
    """Extract citation IDs from the answer string.

    The model is expected to cite chunks using the syntax ``[<chunk_id>]``.
    This function returns the IDs (without brackets) in the order they appear,
    preserving duplicates.
    """
    pattern = re.compile(r"\[([^\[\]]+)\]")
    return pattern.findall(answer)


def resolve_citations(answer: str, chunks: List[Dict[str, Any]]) -> CitationResult:
    """Map citation IDs in *answer* to metadata from *chunks*.

    Args:
        answer: Text generated by the LLM, containing citations like ``[C1]``.
        chunks: List of retrieved chunk dictionaries. Each must contain a unique
            identifier under ``chunk_id`` (or ``id``) and the keys ``file``, ``page``,
            ``start_char`` and ``end_char``.

    Returns:
        ``CitationResult`` with the original answer, a list of valid citation
        mappings, a list of dropped (invalid) IDs, and a flag indicating whether
        any citation was invalid.
    """
    cited_ids = _extract_citation_ids(answer)

    # Build a quick lookup from ID to its relevant metadata.
    id_to_meta: Dict[str, Dict[str, Any]] = {}
    for chunk in chunks:
        cid = chunk.get("chunk_id") or chunk.get("id")
        if cid:
            id_to_meta[cid] = {
                "id": cid,
                "file": chunk.get("file"),
                "page": chunk.get("page"),
                "start_char": chunk.get("start_char"),
                "end_char": chunk.get("end_char"),
            }

    valid: List[Dict[str, Any]] = []
    dropped: List[str] = []
    for cid in cited_ids:
        meta = id_to_meta.get(cid)
        if meta:
            valid.append(meta)
        else:
            dropped.append(cid)

    return CitationResult(
        answer=answer,
        valid_citations=valid,
        dropped_citations=dropped,
        has_invalid=bool(dropped),
    )
